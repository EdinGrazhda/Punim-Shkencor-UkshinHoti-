// Run with PLAYWRIGHT_MODULE=<path-to-playwright> PLAYWRIGHT_BROWSERS_PATH=<browser-cache> node scripts/qa-browser.mjs.
import { mkdir } from "node:fs/promises";

const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ?? "playwright");
const adminEmail = process.env.QA_ADMIN_EMAIL;
const adminPassword = process.env.QA_ADMIN_PASSWORD;
if (!adminEmail || !adminPassword) throw new Error("Set QA_ADMIN_EMAIL and QA_ADMIN_PASSWORD for the seeded test administrator.");
const output = process.env.QA_OUTPUT ?? "/tmp/ckadinti-qa";
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, args: ["--no-sandbox"] });
const errors = [];
const teacher = await browser.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 });
teacher.on("pageerror", error => errors.push(`teacher: ${error.message}`));
await teacher.goto("http://localhost:4173/", { waitUntil: "networkidle" });
await teacher.getByText("Learning feels better when").waitFor();
await teacher.screenshot({ path: `${output}/landing-desktop.png`, fullPage: true });
await teacher.goto("http://localhost:4173/teacher", { waitUntil: "networkidle" });
await teacher.getByText("Teacher sign in", { exact: true }).first().waitFor();
await teacher.goto("http://localhost:4173/register", { waitUntil: "networkidle" });
await teacher.waitForURL("**/login");
await teacher.goto("http://localhost:4173/admin/login", { waitUntil: "networkidle" });
await teacher.getByRole("heading", { name: "Admin sign in" }).waitFor();
await teacher.getByLabel("Email address").fill(adminEmail);
await teacher.getByLabel("Password").fill(adminPassword);
await teacher.getByRole("button", { name: "Sign in", exact: true }).click();
await teacher.getByRole("heading", { name: "Create teacher account" }).waitFor();
await teacher.screenshot({ path: `${output}/admin-dashboard.png`, fullPage: true });
const teacherEmail = `qa-${Date.now()}@example.test`;
await teacher.getByLabel("Teacher name").fill("Ada Teacher");
await teacher.getByLabel("Email address").fill(teacherEmail);
await teacher.getByRole("button", { name: /Create account/i }).click();
await teacher.locator(".admin-credential code").waitFor();
const teacherPassword = (await teacher.locator(".admin-credential code").textContent())?.trim();
if (!teacherPassword) throw new Error("Admin did not receive a temporary teacher password");
await teacher.screenshot({ path: `${output}/admin-created-teacher.png`, fullPage: true });
await teacher.getByRole("button", { name: "Log out" }).click();
await teacher.goto("http://localhost:4173/login", { waitUntil: "networkidle" });
await teacher.getByLabel("Email address").fill(teacherEmail);
await teacher.getByLabel("Password").fill(teacherPassword);
await teacher.getByRole("button", { name: "Sign in", exact: true }).click();
await teacher.getByRole("heading", { name: "Set your password" }).waitFor();
const privatePassword = `qa-private-${Date.now()}-password`;
await teacher.getByLabel("Temporary password").fill(teacherPassword);
await teacher.getByLabel("New password", { exact: true }).fill(privatePassword);
await teacher.getByLabel("Confirm new password").fill(privatePassword);
await teacher.getByRole("button", { name: /Save password/i }).click();
await teacher.getByText("Welcome, Teacher!").waitFor();
await teacher.screenshot({ path: `${output}/teacher-desktop.png`, fullPage: true });
await teacher.getByRole("button", { name: /Create Game/i }).first().click();
await teacher.getByRole("button", { name: /Create live session/i }).click();
await teacher.getByText("JOIN CODE", { exact: true }).waitFor();
const code = (await teacher.locator(".live-info-strip strong").first().textContent())?.trim();
if (!code || code.length !== 6) throw new Error(`Invalid join code: ${code}`);
await teacher.screenshot({ path: `${output}/teacher-live.png`, fullPage: true });

const student = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1 });
student.on("pageerror", error => errors.push(`student: ${error.message}`));
await student.goto("http://localhost:4173/join", { waitUntil: "networkidle" });
await student.getByText("What should we call you?").waitFor();
await student.screenshot({ path: `${output}/student-name-mobile.png`, fullPage: true });
await student.getByLabel("Your name").fill("Ada");
await student.getByRole("button", { name: /Continue to game code/i }).click();
await student.getByLabel("Classroom code").waitFor();
await student.screenshot({ path: `${output}/student-join-mobile.png`, fullPage: true });
await student.getByLabel("Classroom code").fill(code);
await student.getByRole("button", { name: /Join Game/i }).click();
await student.getByText("You're in!").waitFor();
await student.waitForTimeout(450);
await student.screenshot({ path: `${output}/student-lobby-mobile.png`, fullPage: true });

await teacher.getByRole("button", { name: /Start game/i }).click();
await student.getByText("MISSION QUESTION").waitFor();
await student.waitForTimeout(450);
await student.screenshot({ path: `${output}/student-question-mobile.png`, fullPage: true });
const projector = await browser.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 });
projector.on("pageerror", error => errors.push(`projector: ${error.message}`));
await projector.goto(`http://localhost:4173/projector?code=${code}`, { waitUntil: "networkidle" });
await projector.getByText("What is the safest way to create a password?").waitFor();
if (await projector.getByText("Use a long, random combination of letters, numbers and symbols").count()) throw new Error("Projector revealed answer before teacher reveal");
await projector.screenshot({ path: `${output}/projector-question.png`, fullPage: true });
await student.getByRole("button", { name: /Use a long, random combination/i }).click();
await student.getByText("Answer locked in!").waitFor();
await teacher.getByRole("button", { name: /Reveal answer/i }).click();
await student.getByText("Excellent work!").waitFor();
await student.waitForTimeout(450);
await student.screenshot({ path: `${output}/student-feedback-mobile.png`, fullPage: true });
await teacher.screenshot({ path: `${output}/teacher-reveal.png`, fullPage: true });
await projector.getByText("Use a long, random combination of letters, numbers and symbols").waitFor();
await projector.screenshot({ path: `${output}/projector-reveal.png`, fullPage: true });
await teacher.getByRole("button", { name: /End Game/i }).click();
await teacher.getByRole("dialog").getByRole("button", { name: /End Game/i }).click();
await student.getByText("Look how far you've come.").waitFor();
await student.waitForTimeout(450);
await student.screenshot({ path: `${output}/student-results-mobile.png`, fullPage: true });
await student.getByRole("button", { name: /Back to join/i }).click();
await student.getByText("What should we call you?").waitFor();
await student.getByRole("button", { name: /Continue to game code/i }).click();
await student.getByLabel("Classroom code").waitFor();
await teacher.getByRole("button", { name: "Results", exact: true }).click();
await teacher.getByText("Mission results").waitFor();
await teacher.screenshot({ path: `${output}/teacher-results.png`, fullPage: true });
await teacher.getByRole("button", { name: "Log out" }).click();
await teacher.getByText("Learning feels better when").waitFor();
await teacher.goto("http://localhost:4173/login", { waitUntil: "networkidle" });
await teacher.getByLabel("Email address").fill(teacherEmail);
await teacher.getByLabel("Password").fill(privatePassword);
await teacher.getByRole("button", { name: "Sign in", exact: true }).click();
await teacher.getByText("Welcome, Teacher!").waitFor();

if (errors.length) throw new Error(errors.join("\n"));
console.log(JSON.stringify({ passed: true, code, screenshots: output, errors }));
await browser.close();
